#!/usr/bin/env python3
"""Generate INDEX.md, index.json, llms.txt and the runbook copies inside skills.

Usage:
  scripts/build.py            write generated files
  scripts/build.py --dist DIR also write a tarball and per-skill zips into DIR
"""

import argparse
import json
import re
import shutil
import sys
import tarfile
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _lib as lib  # noqa: E402

REF_RE = re.compile(r"references/([a-z0-9]+(?:-[a-z0-9]+)*)\.md")


def render_index(runbooks):
    rows = []
    for rb in runbooks:
        for symptom in rb.fm.get("symptoms", []):
            rows.append((lib.AREAS.index(rb.fm["area"]) if rb.fm.get("area") in lib.AREAS else 99,
                         symptom.lower(), symptom, rb))
    rows.sort(key=lambda r: (r[0], r[1], r[3].id))
    out = [
        "# Symptom index",
        "",
        "Generated by `scripts/build.py`; do not edit. Find the symptom, open the runbook by path.",
        "",
        "| Symptom | Runbook | Risk | Mode |",
        "| - | - | - | - |",
    ]
    for _, _, symptom, rb in rows:
        out.append(f"| {symptom} | [{rb.id}]({rb.rel}) | {rb.fm.get('risk', '?')} | {rb.fm.get('mode', '?')} |")
    return "\n".join(out) + "\n"


def entry(rb):
    keys = ["id", "title", "area", "symptoms", "families", "releases", "mode", "risk",
            "requires_root", "vendor", "verified", "reviewed", "updated"]
    data = {k: rb.fm[k] for k in keys if k in rb.fm}
    data["path"] = rb.rel
    data["tokens"] = lib.tokens(rb.text)
    return data


def render_json(runbooks):
    items = sorted((entry(rb) for rb in runbooks), key=lambda e: e["id"])
    return json.dumps({"runbooks": items}, indent=2, ensure_ascii=False) + "\n"


def render_llms(runbooks):
    out = [
        "# linux4AI",
        "",
        "> Advanced Linux debugging runbooks for L3 engineers on RHEL, SLES and Debian/Ubuntu "
        "enterprise releases. One symptom per runbook; commands are given per distro family.",
        "",
        "Start with [INDEX.md](INDEX.md). Machine-readable catalog: [index.json](index.json).",
    ]
    for area in lib.AREAS:
        items = [rb for rb in runbooks if rb.fm.get("area") == area]
        if not items:
            continue
        out += ["", f"## {area}", ""]
        for rb in sorted(items, key=lambda r: r.id):
            symptoms = "; ".join(rb.fm.get("symptoms", []))
            out.append(f"- [{rb.fm.get('title', rb.id)}]({rb.rel}): {symptoms}")
    return "\n".join(out) + "\n"


def skill_dirs():
    return sorted(p.parent for p in lib.SKILLS.glob("*/SKILL.md"))


def skill_refs(skill_dir):
    text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    return sorted(set(REF_RE.findall(text)))


def expected_skill_files(runbooks):
    """Map generated path -> source path for every skill reference."""
    by_id = {rb.id: rb for rb in runbooks}
    result = {}
    for sd in skill_dirs():
        for rid in skill_refs(sd):
            if rid in by_id:
                result[sd / "references" / f"{rid}.md"] = by_id[rid].path
    return result


def render_all(runbooks):
    return {
        lib.ROOT / "INDEX.md": render_index(runbooks),
        lib.ROOT / "index.json": render_json(runbooks),
        lib.ROOT / "llms.txt": render_llms(runbooks),
    }


def write_all(runbooks):
    for path, content in render_all(runbooks).items():
        path.write_text(content, encoding="utf-8")
    wanted = expected_skill_files(runbooks)
    for sd in skill_dirs():
        refs = sd / "references"
        if refs.exists():
            for f in refs.iterdir():
                if f not in wanted:
                    f.unlink()
    for dst, src in wanted.items():
        dst.parent.mkdir(exist_ok=True)
        shutil.copyfile(src, dst)
    for sd in skill_dirs():
        refs = sd / "references"
        if refs.exists() and not any(refs.iterdir()):
            refs.rmdir()


def write_dist(dist):
    dist.mkdir(parents=True, exist_ok=True)
    zips = dist / "zips"
    zips.mkdir(exist_ok=True)
    tar_path = dist / "linux4ai-skills.tar.gz"
    with tarfile.open(tar_path, "w:gz") as tar:
        for extra in ["LICENSE", "LICENSES", "scripts/install.sh", "docs/INSTALL.md"]:
            if (lib.ROOT / extra).exists():
                tar.add(lib.ROOT / extra, arcname=f"linux4ai/{extra}")
        for sd in skill_dirs():
            tar.add(sd, arcname=f"linux4ai/skills/{sd.name}")
    for sd in skill_dirs():
        with zipfile.ZipFile(zips / f"{sd.name}.zip", "w", zipfile.ZIP_DEFLATED) as z:
            for f in sorted(sd.rglob("*")):
                if f.is_file():
                    z.write(f, arcname=f"{sd.name}/{f.relative_to(sd).as_posix()}")
    print(f"wrote {tar_path} and {len(skill_dirs())} zips in {zips}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dist", type=Path, help="also write release archives into this directory")
    args = parser.parse_args()
    runbooks = lib.load_runbooks()
    write_all(runbooks)
    print(f"built index for {len(runbooks)} runbooks, {len(skill_dirs())} skills")
    if args.dist:
        write_dist(args.dist)


if __name__ == "__main__":
    main()
